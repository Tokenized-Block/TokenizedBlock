/* preparer-deploiement-contest.mjs — FREEZES the deployment transaction of BlockContest (game325, Phil's GO 2026-11-09).
 * ⛔ THIS SCRIPT SIGNS NOTHING AND SENDS NOTHING. It writes ../block-contest-deploiement.js; deployer-block-contest.html offers it to the
 *   connected wallet. Owner config: votes 100 % burned, winner takes all, 3 votes from 3 addresses, 2 qualified entries, pot capped at
 *   862,000 TBLOCK (~$5), weekly rounds (3 d entry + 4 d vote) starting at GENESIS.
 * The 62 pair currencies come from hook-7030-descripteur.js (DEVISES_7030 minus native ETH) and MUST equal test/Pairs7030.sol (the list the
 *   77 unit + 11 fork tests used); otherwise this script refuses.
 * Usage (from contracts/): forge build && node preparer-deploiement-contest.mjs [GENESIS=unix seconds] [SORTIE=path] */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ICI = path.dirname(fileURLToPath(import.meta.url));
const { DEVISES_7030 } = await import(pathToFileURL(path.join(ICI, '..', 'hook-7030-descripteur.js')).href);
const bas = (x) => String(x || '').toLowerCase();
const fromHook = [...new Set((DEVISES_7030 || []).map((d) => bas(typeof d === 'string' ? d : d.adresse || d.address)).filter((a) => /^0x[0-9a-f]{40}$/.test(a) && a !== '0x' + '0'.repeat(40)))];
const fromTests = [...new Set((fs.readFileSync(path.join(ICI, 'test/Pairs7030.sol'), 'utf8').match(/0x[0-9a-fA-F]{40}/g) || []).map(bas))];
const same = fromHook.length === fromTests.length && fromHook.every((a) => fromTests.includes(a));
if (!same || fromHook.length !== 62) throw new Error('pair list mismatch: descriptor ' + fromHook.length + ' vs tests ' + fromTests.length);
const GENESIS = Number(process.env.GENESIS || 1794355200); /* 2026-11-11 00:00:00 UTC */
const C = Object.freeze({
  tblock: '0xB200000000000000000000BA9BF8330307f8830E', hook: '0x32F3f572Dd17625bAb9035789C953E1d001864cc', genesis: GENESIS,
  entryPeriod: 259200, votePeriod: 345600, votePrice: '8621000000000000000000', entryFee: '17241000000000000000000',
  burnBps: 10000, split1: 10000, split2: 0, split3: 0, minVotes: 3, minVoters: 3, minQualifiedEntries: 2, maxPot: '862000000000000000000000',
});
const SIG = 'constructor((address,address,uint64,uint64,uint64,uint256,uint256,uint256,uint256,uint256,uint256,uint256,uint256,uint256,uint256),address[])';
const tuple = '(' + [C.tblock, C.hook, C.genesis, C.entryPeriod, C.votePeriod, C.votePrice, C.entryFee, C.burnBps, C.split1, C.split2, C.split3,
  C.minVotes, C.minVoters, C.minQualifiedEntries, C.maxPot].join(',') + ')';
const args = execFileSync('cast', ['abi-encode', SIG, tuple, '[' + fromHook.join(',') + ']']).toString().trim();
if (!/^0x[0-9a-f]+$/.test(args)) throw new Error('cast abi-encode failed');
const art = JSON.parse(fs.readFileSync(path.join(ICI, 'out/BlockContest.sol/BlockContest.json'), 'utf8'));
const code = String(art.bytecode.object);
const ctor = (art.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
if (ctor.length !== 2 || ctor[0].type !== 'tuple' || ctor[1].type !== 'address[]' || ctor[0].components.length !== 15) throw new Error('constructor shape differs');
const creation = code + args.slice(2);
const src = fs.readFileSync(path.join(ICI, 'src/BlockContest.sol'));
const meta = typeof art.metadata === 'string' ? JSON.parse(art.metadata) : (art.metadata || {});
fs.writeFileSync(process.env.SORTIE || path.join(ICI, '..', 'block-contest-deploiement.js'), `/* block-contest-deploiement.js — GENERATED by contracts/preparer-deploiement-contest.mjs. DO NOT EDIT BY HAND.
 * The UNSIGNED deployment transaction of BlockContest. Nothing here signs or sends. */
export const CONTEST_DEPLOIEMENT = Object.freeze({
  chaine: 8453,
  contrat: 'BlockContest',
  compilateur: ${JSON.stringify((meta.compiler || {}).version || null)},
  config: Object.freeze(${JSON.stringify(C)}),
  devisesPaire: ${fromHook.length},
  sha256Source: '${crypto.createHash('sha256').update(src).digest('hex')}',
  sha256Creation: '${crypto.createHash('sha256').update(creation).digest('hex')}',
  octetsCreation: ${(creation.length - 2) / 2},
  pret: true,
  /* filled after the deployment was READ on chain (status 1, code identical to the fork's) */
  adresse: ${process.env.ADRESSE ? `'${String(process.env.ADRESSE).toLowerCase()}'` : 'null'},
  bloc: ${process.env.BLOC ? Number(process.env.BLOC) : 'null'},
  tx: ${process.env.TX ? `'${String(process.env.TX).toLowerCase()}'` : 'null'},
  creation: '${creation}',
});
`);
console.log('written, bytes', (creation.length - 2) / 2, 'genesis', new Date(GENESIS * 1000).toISOString());
