/* preparer-deploiement-economie.mjs — FREEZES the deployment data of BlockLikes + TBlockVault (Phil 2026-11-10).
 * ⛔ THIS SCRIPT SIGNS NOTHING AND SENDS NOTHING. It writes ../economie-deploiement.js; deployer-economie.html offers it to the
 *   connected wallet, in two signatures: BlockLikes first, then TBlockVault, whose constructor needs the BlockLikes address (the page
 *   appends the 11 static words of the vault config to VAULT_INIT, the likes address read from the first receipt).
 * Prices were set from the pool price read on 2026-11-10 (1 TBLOCK ~ $0.0000058085): +1 = 86,000 TBLOCK (~$0.50), hold to like
 *   2,580,000 (~$15), hold to claim 17,200,000 (~$100). They are FIXED in TBLOCK once deployed; the dollar value moves with the price.
 * Usage (from contracts/): forge build && node preparer-deploiement-economie.mjs */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const ICI = path.dirname(fileURLToPath(import.meta.url));
const CAST = path.join(process.env.USERPROFILE || process.env.HOME || '', '.foundry', 'bin', process.platform === 'win32' ? 'cast.exe' : 'cast');
const TBLOCK = '0xB200000000000000000000BA9BF8330307f8830E';
const CONTEST = '0x001ead57218f3ab79e2dcacb05ddfc4574ef177c';
const GENESIS = 1794355200; /* 2026-11-11 00:00:00 UTC = the contest GENESIS: epochs line up with contest rounds (7 days) */
const LIKES = Object.freeze({ tblock: TBLOCK, likePrice: '86000000000000000000000', minHold: '2580000000000000000000000', genesis: GENESIS, epoch: 604800 });
const VAULT = Object.freeze({ tblock: TBLOCK, contest: CONTEST, minHold: '17200000000000000000000000', rewardBps: 5000, topBps: 2000, rebateBps: 5000,
  maxEpochBudget: '50000000000000000000000000', claimWindow: 1209600, maxFeedPerCall: '862000000000000000000000', feedCooldown: 86400,
  /* Phil 2026-11-10: the two rescue wallets = the TBLOCK dev wallet (address as Phil wrote it) and Grok's */
  dev: '0x264496cc303f8dbe49a241ea84cd42be8392bc80', dev2: '0x31e0dbc9038c82184b9fa6a90057a3ed500bde3b' });
const art = (n) => JSON.parse(fs.readFileSync(path.join(ICI, 'out', n + '.sol', n + '.json'), 'utf8'));
const L = art('BlockLikes'), V = art('TBlockVault'), B = art('TBlockBuybackV2');
/* buyback v2: the SAME parameters as the reviewed, fork-tested, deployed v1 (tblock-buyback-deploiement.js), plus dest = the vault */
const { BUYBACK_DEPLOIEMENT: B1 } = await import(new URL('../tblock-buyback-deploiement.js', import.meta.url).href);
const BUYBACK = Object.freeze({ ...B1.parametres });
const bc = (B.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
const bnames = bc.length === 1 && bc[0].type === 'tuple' ? bc[0].components.map((x) => x.name).join() : '';
if (bnames !== 'poolManager,v4Key,v3Pool,weth,wtcoin,tblock,keeper,publicDelay,maxPerCall,minSpend,cooldown,twapWindow,maxV3DevTicks,maxV4ImpactTicks,maxHookPpm,tipBps,maxTip,dest')
  throw new Error('TBlockBuybackV2 constructor shape differs: ' + bnames);const lc = (L.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
const vc = (V.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
if (lc.map((x) => x.type).join() !== 'address,uint256,uint256,uint64,uint64') throw new Error('BlockLikes constructor shape differs');
if (vc.length !== 1 || vc[0].type !== 'tuple' || vc[0].components.map((x) => x.name + ':' + x.type).join() !==
  'tblock:address,likes:address,contest:address,minHold:uint256,rewardBps:uint256,topBps:uint256,rebateBps:uint256,maxEpochBudget:uint256,claimWindow:uint256,maxFeedPerCall:uint256,feedCooldown:uint256,dev:address,dev2:address')
  throw new Error('TBlockVault constructor shape differs');
const largs = execFileSync(CAST, ['abi-encode', 'constructor(address,uint256,uint256,uint64,uint64)', LIKES.tblock, LIKES.likePrice, LIKES.minHold, String(LIKES.genesis), String(LIKES.epoch)]).toString().trim();
if (!/^0x[0-9a-f]{320}$/.test(largs)) throw new Error('cast abi-encode failed');
const likesCreation = String(L.bytecode.object) + largs.slice(2);
const vaultInit = String(V.bytecode.object);
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const meta = typeof L.metadata === 'string' ? JSON.parse(L.metadata) : (L.metadata || {});
fs.writeFileSync(path.join(ICI, '..', 'economie-deploiement.js'), `/* economie-deploiement.js — GENERATED by contracts/preparer-deploiement-economie.mjs. DO NOT EDIT BY HAND.
 * The UNSIGNED deployment data of BlockLikes and TBlockVault. Nothing here signs or sends. */
export const ECONOMIE_DEPLOIEMENT = Object.freeze({
  chaine: 8453,
  compilateur: ${JSON.stringify((meta.compiler || {}).version || null)},
  likes: Object.freeze({ config: Object.freeze(${JSON.stringify(LIKES)}), sha256Source: '${sha(fs.readFileSync(path.join(ICI, 'src/BlockLikes.sol')))}',
    sha256Creation: '${sha(likesCreation)}', octets: ${(likesCreation.length - 2) / 2}, creation: '${likesCreation}' }),
  vault: Object.freeze({ config: Object.freeze(${JSON.stringify(VAULT)}), sha256Source: '${sha(fs.readFileSync(path.join(ICI, 'src/TBlockVault.sol')))}',
    sha256Init: '${sha(vaultInit)}', octets: ${(vaultInit.length - 2) / 2 + 13 * 32}, init: '${vaultInit}' }),
  buyback: Object.freeze({ config: Object.freeze(${JSON.stringify(BUYBACK)}), sha256Source: '${sha(fs.readFileSync(path.join(ICI, 'src/buyback/TBlockBuybackV2.sol')))}',
    sha256Init: '${sha(String(B.bytecode.object))}', octets: ${(String(B.bytecode.object).length - 2) / 2 + 22 * 32}, init: '${String(B.bytecode.object)}' }),
  /* filled after each deployment was READ on chain */
  adresseLikes: null,
  adresseVault: null,
  adresseBuyback: null,
});
`);
console.log('written: likes', (likesCreation.length - 2) / 2, 'bytes; vault init', (vaultInit.length - 2) / 2, 'bytes');
