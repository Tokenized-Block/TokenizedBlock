/* preparer-deploiement-buyback.mjs — FREEZES the deployment transaction of TBlockBuyback (game324, Phil's GO 2026-11-09).
 * ⛔ THIS SCRIPT SIGNS NOTHING AND SENDS NOTHING. It writes ../tblock-buyback-deploiement.js; deployer-tblock-buyback.html offers it to the
 *   CONNECTED wallet (Grok's, on Phil's order). What is signed is what was proven: banc-buyback-deploy-fork sends THIS data on a fork.
 * Constructor: one tuple (see TBlockBuyback.sol / the ABI read from the forge artifact below). Values = the tested config (40 tests,
 *   3 independent reviews). KEEPER = Grok's wallet 0x31e0…bde3b (it also created the UNIT block on hook 7030, read on chain).
 * Usage (from contracts/): forge build && node preparer-deploiement-buyback.mjs [SORTIE=path] */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const ICI = path.dirname(fileURLToPath(import.meta.url));
const SIG = 'constructor((address,(address,address,uint24,int24,address),address,address,address,address,address,uint256,uint256,uint256,uint256,uint32,int24,int24,uint24,uint16,uint256))';
export const PARAMS = Object.freeze({
  poolManager: '0x498581fF718922c3f8e6A244956aF099B2652b2b',
  v4Key: ['0x5cDa0E1CA4ce2af96315f7F8963C85399c172204', '0xB200000000000000000000BA9BF8330307f8830E', 3000, 60, '0x3e6B46810b1fd5085086Fd1417E8adB02f34a044'],
  v3Pool: '0x8495444b5f3699D223baa01E67Bf534475620aff',
  weth: '0x4200000000000000000000000000000000000006',
  wtcoin: '0x5cDa0E1CA4ce2af96315f7F8963C85399c172204',
  tblock: '0xB200000000000000000000BA9BF8330307f8830E',
  keeper: '0x31e0dbc9038c82184b9fa6a90057a3ed500bde3b',
  publicDelay: 21600, maxPerCall: '2000000000000000', minSpend: '100000000000000', cooldown: 3600, twapWindow: 1800,
  maxV3DevTicks: 100, maxV4ImpactTicks: 60, maxHookPpm: 12000, tipBps: 50, maxTip: '20000000000000',
});
const P = PARAMS;
const tuple = '(' + [P.poolManager, '(' + P.v4Key.join(',') + ')', P.v3Pool, P.weth, P.wtcoin, P.tblock, P.keeper, P.publicDelay, P.maxPerCall,
  P.minSpend, P.cooldown, P.twapWindow, P.maxV3DevTicks, P.maxV4ImpactTicks, P.maxHookPpm, P.tipBps, P.maxTip].join(',') + ')';
const args = execFileSync('cast', ['abi-encode', SIG, tuple]).toString().trim();
if (!/^0x[0-9a-f]+$/.test(args)) throw new Error('cast abi-encode failed');
const art = JSON.parse(fs.readFileSync(path.join(ICI, 'out/TBlockBuyback.sol/TBlockBuyback.json'), 'utf8'));
const code = String(art.bytecode.object);
if (!/^0x[0-9a-f]+$/.test(code)) throw new Error('bytecode missing in the forge artifact');
const ctor = (art.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
if (ctor.length !== 1 || ctor[0].type !== 'tuple') throw new Error('constructor shape differs from the one encoded here');
const src = fs.readFileSync(path.join(ICI, 'src/buyback/TBlockBuyback.sol'));
const creation = code + args.slice(2);
const out = `/* tblock-buyback-deploiement.js — GENERATED by contracts/preparer-deploiement-buyback.mjs. DO NOT EDIT BY HAND.
 * The UNSIGNED deployment transaction of TBlockBuyback. Nothing here signs or sends. */
export const BUYBACK_DEPLOIEMENT = Object.freeze({
  chaine: 8453,
  contrat: 'TBlockBuyback',
  compilateur: ${JSON.stringify((JSON.parse(typeof art.metadata === 'string' ? art.metadata : JSON.stringify(art.metadata || {})).compiler || {}).version || null)},
  parametres: Object.freeze(${JSON.stringify(PARAMS)}),
  sha256Source: '${crypto.createHash('sha256').update(src).digest('hex')}',
  sha256Creation: '${crypto.createHash('sha256').update(creation).digest('hex')}',
  octetsCreation: ${(creation.length - 2) / 2},
  pret: true,
  /* filled after the deployment was READ on chain (status 1, from the keeper wallet, code identical to the fork's) */
  adresse: ${process.env.ADRESSE ? `'${String(process.env.ADRESSE).toLowerCase()}'` : 'null'},
  bloc: ${process.env.BLOC ? Number(process.env.BLOC) : 'null'},
  tx: ${process.env.TX ? `'${String(process.env.TX).toLowerCase()}'` : 'null'},
  creation: '${creation}',
});
`;
const sortie = process.env.SORTIE || path.join(ICI, '..', 'tblock-buyback-deploiement.js');
fs.writeFileSync(sortie, out);
console.log('written', sortie, 'bytes', (creation.length - 2) / 2);
